import {test,expect} from '@playwright/test';
const uid=n=>`50000000-0000-0000-0000-${String(n).padStart(12,'0')}`;

test('approved design preserves messages and controls on desktop and mobile',async({page},testInfo)=>{
  const errors=[],now=Date.now(),profile={id:uid(1),displayName:'Marco'},group={id:uid(3),ownerId:uid(1),name:'Turma de sexta',member:true,memberCount:3};
  const bet={id:uid(4),groupId:group.id,authorId:profile.id,question:'Vai chover no encontro?',type:'BINARY',minimumPoints:10,state:'OPEN',publishedAt:new Date(now-60000).toISOString(),endsAt:new Date(now+3600000).toISOString(),predictionsCloseAt:new Date(now+1800000).toISOString(),authorCancelUntil:new Date(now+300000).toISOString(),options:[{id:uid(5),label:'Sim',position:0},{id:uid(6),label:'Não',position:1}]};
  const custom={nameColor:'#123456',title:'Mestre',titleColor:'#654321'};
  const messageTime=new Date(2026,10,15,12).getTime();
  const message=(id,authorId,minutes,deleted=false)=>({id,authorId,displayName:authorId===profile.id?'Marco':'Ana',body:deleted?null:`Mensagem ${id} da turma.`,sentAt:new Date(messageTime+minutes*60000).toISOString(),deleted,betId:null,...custom});
  const messages=[message(1,profile.id,0),message(2,profile.id,1),message(3,uid(2),2),message(4,uid(2),3),message(5,uid(2),9),message(6,uid(2),10,true),message(7,uid(2),11)];
  const aggregates={betId:bet.id,totalVotes:4,options:bet.options.map((option,i)=>({optionId:option.id,label:option.label,position:i,votes:i===0?3:1}))};
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(session=>sessionStorage.setItem('gamblr.session',JSON.stringify(session)),{access_token:'owner',refresh_token:'owner',expires_at:Math.floor(now/1000)+3600,user:{email:'marco@example.test',user_metadata:{display_name:'Marco'}}});
  await page.route('**/status',route=>route.fulfill({json:{writer:true,reader:true}}));
  await page.route('**/reader/api/**',route=>{
    const path=new URL(route.request().url()).pathname;
    if(path.endsWith('/participation'))return route.fulfill({json:{groupId:group.id,bets:[aggregates]}});
    if(path.endsWith('/ranking'))return route.fulfill({json:{groupId:group.id,ranking:[{userId:profile.id,displayName:'Marco',position:1,availablePoints:'100',...custom},{userId:uid(2),displayName:'Ana',position:2,availablePoints:'85'},{userId:uid(8),displayName:'Bia',position:3,availablePoints:'70'}]}});
    return route.fulfill({json:{...aggregates,groupId:group.id,version:'v1',options:aggregates.options.map(option=>({...option,decimalOdds:'2.00'}))}});
  });
  await page.route('**/writer/api/**',route=>{
    const path=new URL(route.request().url()).pathname;let json={};
    if(path.endsWith('/api/me'))json=profile;
    else if(path.endsWith('/api/groups')||path.endsWith('/api/groups/public'))json=[group];
    else if(path.endsWith('/api/friendships')||path.endsWith('/api/group-invitations'))json=[];
    else if(path.endsWith('/settings'))json={...group,myRole:'OWNER',canInvite:true};
    else if(path.endsWith('/wallet/me'))json={availablePoints:100,reservedPoints:0};
    else if(path.endsWith('/bets'))json=[{bet,myPrediction:null}];
    else if(path.endsWith('/messages'))json={messages,nextBefore:null,canModerate:true};
    else if(path.endsWith('/resolution'))json={state:'OPEN',phase:'IN_PROGRESS',resultDeadline:new Date(now+7200000).toISOString(),pendingContests:0,canCancel:false,canPublishResult:false,canContest:false,canDecide:false};
    else return route.fulfill({status:404,json:{code:'NOT_FOUND',message:'Não encontrado.'}});
    return route.fulfill({json});
  });
  await page.goto('/');
  await expect(page.locator('html')).not.toHaveAttribute('data-appearance',/.*/);
  await expect(page.locator('html')).not.toHaveAttribute('data-sidebar-layout',/.*/);
  await expect(page.locator('#group-thread .chat-message')).toHaveCount(7);
  await expect(page.locator('#group-thread .message-heading')).toHaveCount(7);
  await expect(page.locator('#group-thread time')).toHaveCount(7);
  await expect(page.locator('#group-thread .delete-message')).toHaveCount(6);
  await expect(page.locator('#group-thread .message-continuation')).toHaveCount(2);
  await expect(page.locator('#group-thread .chat-message[data-message="6"]')).toContainText('Mensagem apagada pela moderação.');
  await expect(page.locator('.chat-window').first()).toHaveCSS('border-radius','8px');
  await expect(page.locator('#page-title')).toHaveCSS('font-size','25px');
  await expect(page.locator('body')).toHaveCSS('font-family',/Arial/);
  await expect(page.locator('#ranking-list .me .group-person > span').first()).toHaveCSS('color','rgb(18, 52, 86)');
  await expect(page.locator('#ranking-list .me .group-title')).toHaveCSS('color','rgb(101, 67, 33)');
  await expect(page.locator('#bets-list .participation-legend')).toContainText('75%');
  await expect(page.locator('#delete-bet-button')).toHaveCSS('color','rgb(139, 69, 69)');
  await page.locator('#group-message').focus();
  await expect(page.locator('#group-message')).toHaveCSS('border-radius','5px');
  await page.locator('#group-thread').evaluate(thread=>thread.scrollTop=0);
  await page.screenshot({path:testInfo.outputPath('design-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await expect(page.locator('#group-thread .chat-message')).toHaveCount(7);
  await page.screenshot({path:testInfo.outputPath('design-mobile.png'),fullPage:true});
  await page.locator('#feed-button').click();await expect(page.locator('#page-subtitle')).toHaveText('Apostas dos grupos em que você participa.');
  await expect(page.locator('#feed-list .feed-bet-card')).toHaveCount(1);
  expect(errors).toEqual([]);
});
